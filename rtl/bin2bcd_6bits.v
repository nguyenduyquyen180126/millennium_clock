            6'b101101: bcd = 8'b0100_0101;
            6'b101110: bcd = 8'b0100_0110;
            6'b101111: bcd = 8'b0100_0111;
            6'b110000: bcd = 8'b0100_1000;
            6'b110001: bcd = 8'b0100_1001;
            6'b110010: bcd = 8'b0101_0000;
            6'b110011: bcd = 8'b0101_0001;
            6'b110100: bcd = 8'b0101_0010;
            6'b110101: bcd = 8'b0101_0011;
