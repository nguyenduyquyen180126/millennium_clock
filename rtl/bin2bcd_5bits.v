module bin2bcd_5bits(
    input wire [4:0] binary,
    output reg [7:0] bcd
);
    always @(*) begin
        case(binary)
            5'b00000: bcd = 8'b0000_0000; // 0
            5'b00001: bcd = 8'b0000_0001; // 1
            5'b00010: bcd = 8'b0000_0010; // 2
            5'b00011: bcd = 8'b0000_0011; // 3
            5'b00100: bcd = 8'b0000_0100; // 4
            5'b00101: bcd = 8'b0000_0101; // 5
            5'b00110: bcd = 8'b0000_0110; // 6
            5'b00111: bcd = 8'b0000_0111; // 7
            5'b01000: bcd = 8'b0000_1000; // 8
            5'b01001: bcd = 8'b0000_1001; // 9
            5'b01010: bcd = 8'b0001_0000; // 10
            5'b01011: bcd = 8'b0001_0001; // 11
            5'b01100: bcd = 8'b0001_0010; // 12
            5'b01101: bcd = 8'b0001_0011; // 13
            5'b01110: bcd = 8'b0001_0100; // 14
            5'b01111: bcd = 8'b0001_0101; // 15
            5'b10000: bcd = 8'b0001_0110; // 16
            5'b10001: bcd = 8'b0001_0111; // 17
            5'b10010: bcd = 8'b0001_1000; // 18
            5'b10011: bcd = 8'b0001_1001; // 19
            5'b10100: bcd = 8'b0010_0000; // 20
            5'b10101: bcd = 8'b0010_0001; // 21
            5'b10110: bcd = 8'b0010_0010; // 22
            5'b10111: bcd = 8'b0010_0011; // 23
            5'b11000: bcd = 8'b0010_0100; // 24
            5'b11001: bcd = 8'b0010_0101; // 25
            5'b11010: bcd = 8'b0010_0110; // 26
            5'b11011: bcd = 8'b0010_0111; // 27
            5'b11100: bcd = 8'b0010_1000; // 28
            5'b11101: bcd = 8'b0010_1001; // 29
            5'b11110: bcd = 8'b0011_0000; // 30
            5'b11111: bcd = 8'b0011_0001; // 31
            default:  bcd = 8'b0000_0000;
        endcase
    end
endmodule
